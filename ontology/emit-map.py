STATUS_CLASS = {"derived": "ok", "gated": "risk", "partial": "info",
                "unguarded": "warn", "violated": "risk"}
GUARD_ORDER = ("unguarded", "partial", "gated", "derived")


def extractors() -> dict:
    spec = importlib.util.spec_from_file_location("onto_extract", HERE / "extract.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return {name: fn() for name, fn in mod.EXTRACTORS.items()}


def e(s) -> str:
    return html.escape(str(s), quote=False)



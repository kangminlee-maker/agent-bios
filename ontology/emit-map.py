def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the page has drifted from its source")
    ap.add_argument("-o", "--out", type=pathlib.Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    graph = json.loads(GRAPH.read_text(encoding="utf-8"))
    page = build(graph, extractors())

    if args.check:
        if not args.out.is_file():
            print(f"FAIL: {args.out} does not exist (run emit-map.py)", file=sys.stderr)
            sys.exit(1)
        if args.out.read_text(encoding="utf-8") != page:
            print(f"FAIL: {args.out} is stale vs instances/graph.json (run emit-map.py)", file=sys.stderr)
            sys.exit(1)
        print(f"emit-map: OK ({args.out.name} matches graph.json)")
        return

    args.out.write_text(page, encoding="utf-8")
    print(f"emit-map: wrote {args.out} — {len(graph['entities'])} entities, "
          f"{len(graph['relationships'])} edges, {len(graph['golden_relationships'])} golden relationships")


if __name__ == "__main__":
    main()

"""Scenarios: the joined bytes a case runs, generated from a short spec.

A case that drives an operation needs more than records that each pass their schema. The request
must name the digest of the payload beside it, the result must answer that request, and an id
must be the same one from step to step. Written by hand those joins drift, and two workers reading
one case fill them in differently. So a case's scenario is a spec (`spec.json`, shaped by
`scenario.schema.json`) and this module writes the joined bytes (`scenario.json`) beside it. The
spec, this module and the generated file together are the case's fixture.

Every record in a spec is a contract example with the leaves the case changes, so the examples
are the vocabulary and a spec states only differences. A record may instead derive from another
record of the same spec (`from` a bare name), which is how a second request repeats the first
with a new id and payload. A string value may name instead of state:

  "@name"          the id `name`: its prefix and 32 hex digits derived from the case and the name
  "#name"          the digest of the record `name` as this scenario builds it, or of the bytes
                   of the member `name`
  "$shape:name"    a value the owner mints — an id it assigns, a time, a count, the digest of
                   what it wrote. Its first place is in a record a step's answer returns. The
                   generated bytes carry a stand-in that satisfies the schema there (shape is an
                   id prefix, `digest`, `instant` or `integer`).

`members` states the bytes of source members a scenario names, and `#name` is their sha256. A
read that returns a member's body (an operation whose row returns `source_member`) names it among
the records its answer returns, so what the reader returns is those bytes, not only their digest.

`joins` in the generated file lists every place a name was resolved, so a driver can put the
owner's real value in each minted place, and recompute every digest over it and each size stated
beside one, before submitting.
A digest of a record a step returns is likewise the digest of what the owner actually returned.
Signing is the person's side, and the driver acts for the person: a key binding's public key and
a signature envelope's `sshsig` stand for what the driver's own key for that binding makes. The
driver holds one key per bound key and signs each envelope's `signed_digest` with it at run time,
so a signature verifies exactly when the bytes it names are the bytes it was made over.
A profile runs a case against the real files of its node and of the nodes its node depends on. A
step whose operation belongs to any other node (team.found in a case M1 runs, when M1 depends on
no Team node) is given: the driver answers it with the step's stated answer and places the
records it returns as given state, and a given step is never evidence about its own owner. The
profile a scenario runs on starts at the access generation its first request states: before the
first step the driver brings a new profile there through restrictions and re-entries of its own,
which are given. From there the generation moves only as the scenario's own steps move it.
A committed step's receipt is generated too, as the record `<step>_receipt` its result names:
the owner mints its sequence and time. Its head is the digest of the record the step stored
when the answer's `head` names one it returns (a collection's head is the collection record its
change stored), and otherwise a digest the owner mints under that name, which a later request's
base expects as `$digest:<head>`. A later operation.query can return the receipt by
that name, and a record the step's own answer returns may name it too. A step that `replays` an
earlier one resubmits the same request bytes and is answered with that step's result and receipt;
the owner writes nothing new. An answer under a new request id that the owner settles as a
duplicate states `receipt_of` the earlier committed step instead, and no receipt is written for it.

`world` is the harness around the steps, never a contract record: isolated processes, each step
naming the one it runs on; a controlled clock that each step may move forward, the generated step
stating the instant it runs at; partitions between two processes over a run of steps; and faults,
each killing the process of one answered step at a fault point B03 names and restarting it, so
that step's answer is what the owner returns for the same request after the restart — or, when
the fault names the step that `observed_by` it, what the owner committed, which the caller first
learns from that later query because no reply reached it. `during` runs one step while another is
in flight: after the owner admitted the other's request and before it answers. `events` are the
outside changes the harness makes between steps, each of a kind the spec's schema closes: a file
edited in the checkout a step reads, received package bytes that differ from what the inventory
advertises, a provider's token refresh arriving with no local transition, the key files arranged
beside or away from the agent or back as the runtime expects, a store setting, a build of the
checkout, an inventory of the checkout, the installed target or the knowledge package the product
ships, a provider's reply to a step that never arrives, and the repository identity a carrier
provider reports. A step may name the concrete `route` its request is submitted through, a row of
the entrance dispositions, with the root a caller chose instead of its own where that route takes
one. A runner step names a situation of the same case in the runner's preflight cases instead of a
request.

What can be decided from the spec alone is checked here and fails by name:
  - every record resolves, and every name it uses is defined;
  - an answered step's request and payload pass their schemas in submit mode, as does each
    record its `submits` names (a new policy a founding proposal names), and every other record
    it carries passes in stored mode; a refused step's records fail with exactly the refusals it
    states;
  - the digests a request names are exactly those of the records the step carries, apart from
    records an earlier step returned and values it minted; a carried record the request does not
    name must be named by its payload, or by a carried record so named (a batch's item requests
    and their payloads);
  - the payload is a kind its operation takes (no payload when it takes none), and every record
    the answer returns is a kind the operation returns;
  - every request states the effect class, grant action and kind of target its operation's row
    declares, the effect class aside when the answer is `effect_class_mismatch`;
  - the result built from the answer passes the result schema, so an answer the contract cannot
    give — a commit beside a gap that prevents one — cannot be written in a spec either;
  - a minted value is used only after the step whose answer first returns it;
  - the world's processes, partitions and faults name steps and processes that exist, a fault
    names a B03 fault point and an answered step, and a runner step a situation of its case;
  - a fault's observer is a later step that returns the faulted step's result; a step that runs
    during another is listed immediately before it, and the other's request uses nothing it mints;
  - an event names a step and records that exist, a file edit states bytes or absence and not
    both, an inventory yields a record or equals one an earlier inventory yielded, a lost reply
    names an answered step, and a route is a row of the entrance dispositions, overriding the
    root only where its disposition takes the root from the caller;
  - an answer's `receipt_of` names an earlier committed step, and such an answer states no head;
  - every member is named by a record or returned by a step, and a size stated beside the digest
    of a record or member of the scenario is that record's canonical size or the member's size;
  - a committed answer states the local effect `committed` (C03's meaning of the value).

  python3 gates/workenv/scenarios.py [CASE ...]           # write scenario.json from each spec
  python3 gates/workenv/scenarios.py --check [CASE ...]   # fail when one differs from its spec

A CASE is a case id or its directory name; none means every spec.
"""
